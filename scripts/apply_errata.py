def main():
    apply = len(sys.argv) > 1 and sys.argv[1] == "apply"
    with io.open(SRC, encoding="utf-8") as f:
        text = f.read()
    misses, hits, ambiguous = [], 0, []
    for old, new in R:
        c = text.count(old)
        if c == 0:
            misses.append(old)
            continue
        if c > 1 and "\n" not in old and len(old) < 12:
            ambiguous.append((old, c))
        text = text.replace(old, new)
        hits += 1
    # Post-pass: collapse any residual double vowel-points (adjacent komets+pasekh
    # in either order = OCR artifact) to a single komets. Explicit single-mark
    # fixes (e.g. פאַרן) already ran above, so they are untouched here.
    before = text.count("ַָ") + text.count("ַָ")
    text = text.replace("ַָ", "ָ").replace("ַָ", "ָ")
    # …then the yud-for-hyphen + ellipsis that sat on top of a collapsed cluster:
    for old, new in [("נישטאָינאָך", "נישטאָ-נאָך"),
                     ("פון די דורות שפּעטער..", "פון די דורות שפּעטער...")]:
        text = text.replace(old, new)
    print(f"residual double-points collapsed: {before}")
    print(f"replacements defined : {len(R)}")
    print(f"applied (>=1 match)  : {hits}")
    print(f"MISSED (0 matches)   : {len(misses)}")
    for m in misses:
        print("   MISS:", repr(m[:60]))
    if ambiguous:
        print(f"multi-match (check)  : {len(ambiguous)}")
        for a, c in ambiguous:
            print(f"   x{c}:", repr(a[:40]))
    if apply:
        with io.open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"\nWROTE {OUT}")
    else:
        print("\n(dry run — pass 'apply' to write esterke_final.txt)")

if __name__ == "__main__":
    main()
